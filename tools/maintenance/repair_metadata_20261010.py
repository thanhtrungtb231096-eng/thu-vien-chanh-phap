"""Apply verified bibliographic corrections and reindex only the three editions.

Original DOC files are never written. Backups include generated text, catalogs
and affected SQLite records so that the repair remains reviewable.
"""
from pathlib import Path
import argparse, sys, json, hashlib, shutil, sqlite3, subprocess, re
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'app'))
from project_paths import WEB, GENERATED, STATE, BUILD, CONFIG
sys.path.insert(0,str(BUILD))
from build_library_index import catalog, publish
from text_normalize import normalize

def run(backup):
    backup=backup.resolve()
    if backup.is_relative_to(ROOT.resolve()):
        raise ValueError('Store metadata backups outside the project directory.')
    overrides=json.loads((CONFIG/'edition_metadata.json').read_text(encoding='utf-8'))
    target=GENERATED/'dai-tang-kinh/catalog.json'
    manifest=json.loads(target.read_text(encoding='utf-8'))
    books=[b for b in manifest['books'] if b['filename'] in overrides]
    assert len(books)==3
    backup.mkdir(parents=True,exist_ok=True)
    paths=[target,WEB/'js/dai-tang-kinh-data.js',GENERATED/'library-audit.json']
    paths += [GENERATED/'dai-tang-kinh/text'/f"{b['id']}.md" for b in books]
    for path in paths:
        saved=backup/path.name
        if not saved.exists():shutil.copy2(path,saved)
    with sqlite3.connect(STATE/'search.sqlite3') as db:
        docrows=[];passages=[]
        for b in books:
            rows=db.execute('SELECT doc,book_key,mode,meta FROM documents WHERE book_key=?',('ebooks:'+b['id'],)).fetchall()
            docrows.extend(rows)
            for row in rows:passages.extend(db.execute('SELECT pid,doc,block,chapter,page,text FROM passages WHERE doc=?',(row[0],)).fetchall())
        saved=backup/'index-records.json'
        if not saved.exists():saved.write_text(json.dumps({'documents':docrows,'passages':passages},ensure_ascii=False),encoding='utf-8')
        for b in books:
            raw=(GENERATED/'dai-tang-kinh/text'/f"{b['id']}.md").read_text(encoding='utf-8')
            assert all(re.sub(r'\s+',' ',s) in re.sub(r'\s+',' ',raw) for s in overrides[b['filename']]['evidence']),b['id']
        for b in books:
            value=overrides[b['filename']]
            path=GENERATED/'dai-tang-kinh/text'/f"{b['id']}.md"
            raw=path.read_text(encoding='utf-8')
            raw=raw.split('\n',1)[1]
            # Replace only the synthetic title. Source transcription stays intact.
            path.write_text('# '+value['title']+'\n'+raw,encoding='utf-8')
            b.update({k:v for k,v in value.items() if k!='evidence'})
            assert b['proofread'] is False
        target.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
        (WEB/'js/dai-tang-kinh-data.js').write_text('/* Generated by build_ebooks.py. */\nwindow.DAI_TANG_KINH_DATA = '+json.dumps(manifest['books'],ensure_ascii=False)+';\nwindow.DAI_TANG_KINH_GROUPS = '+json.dumps(manifest['groups'],ensure_ascii=False)+';\n',encoding='utf-8')
        ids={b['id'] for b in books}
        entries=[e for e in catalog('ebooks') if e['id'] in ids]
        parsed=subprocess.run(['node',str(BUILD/'index_documents.cjs')],input='\n'.join(json.dumps(e,ensure_ascii=False) for e in entries),text=True,encoding='utf-8',capture_output=True,check=True)
        for line in parsed.stdout.splitlines():
            entry=json.loads(line);blocks=entry.pop('blocks')
            docid,oldmeta=db.execute('SELECT doc,meta FROM documents WHERE book_key=? AND mode=?',(entry['key'],entry['mode'])).fetchone()
            meta=json.loads(oldmeta)
            meta.update(entry);meta['headings']=[{'block':b['id'],'title':b['heading']['title'],'level':b['heading']['level']} for b in blocks if b.get('heading')]
            for pid,text in db.execute('SELECT pid,text FROM passages WHERE doc=?',(docid,)).fetchall():
                db.execute("INSERT INTO fulltext(fulltext,rowid,normalized) VALUES('delete',?,?)",(pid,normalize(text)))
            db.execute('DELETE FROM passages WHERE doc=?',(docid,))
            db.execute('UPDATE documents SET meta=? WHERE doc=?',(json.dumps(meta,ensure_ascii=False),docid))
            chapter='';page=None
            for block in blocks:
                if block.get('heading'):
                    chapter=block['heading']['title'];match=re.fullmatch(r'Trang (\d+)',chapter)
                    if match:page=int(match[1])
                for start in range(0,len(block['text']),1300):
                    part=block['text'][start:start+1450]
                    pid=db.execute('INSERT INTO passages(doc,block,chapter,page,text) VALUES(?,?,?,?,?)',(docid,block['id'],chapter,page,part)).lastrowid
                    db.execute('INSERT INTO fulltext(rowid,normalized) VALUES(?,?)',(pid,normalize(part)))
        db.commit()
    publish(STATE/'search.sqlite3')
    print(json.dumps({'corrected':[b['id'] for b in books],'originalSourcesUnchanged':True},ensure_ascii=False))

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--backup-dir',type=Path,required=True,help='Backup directory outside the project')
    run(parser.parse_args().backup_dir)
