"""Produce one initial stylesheet, preserving reviewed cascade order and URLs."""
from pathlib import Path
import json,re,sys

BOOTSTRAP=next(p/folder for p in Path(__file__).resolve().parents for folder in ('app','web-thuvien') if (p/folder/'project_paths.py').is_file())
sys.path.insert(0,str(BOOTSTRAP))
from project_paths import WEB,CONFIG

def build():
    names=json.loads((CONFIG/'stylesheets.json').read_text(encoding='utf-8'))
    if len(names)!=len(set(names)):
        raise ValueError('Duplicate stylesheet in cascade manifest')
    chunks=['/* Generated by build_css_bundle.py. Edit the component sources. */']
    for name in names:
        path=WEB/'css'/name
        if path.parent!=WEB/'css' or path.suffix!='.css' or name=='library.bundle.css':
            raise ValueError('Invalid component stylesheet')
        source=path.read_text(encoding='utf-8-sig')
        if re.search(r'@(?:import|charset)\b',source):
            raise ValueError('Resolve CSS import/charset before bundling '+name)
        chunks.append('/* Component: '+name+' */\n'+source)
    (WEB/'css/library.bundle.css').write_text('\n\n'.join(chunks)+'\n',encoding='utf-8')
    html=(WEB/'index.html').read_text(encoding='utf-8')
    pattern=r'^[ \t]*<link rel="stylesheet" href="css/[^"?]+(?:\?[^" ]*)?">[ \t]*\r?\n'
    matches=list(re.finditer(pattern,html,re.MULTILINE))
    if not matches:
        raise ValueError('No initial stylesheet found')
    for match in reversed(matches[1:]):
        html=html[:match.start()]+html[match.end():]
    first=matches[0]
    html=html[:first.start()]+'  <link rel="stylesheet" href="css/library.bundle.css">\n'+html[first.end():]
    (WEB/'index.html').write_text(html,encoding='utf-8')
    print(json.dumps({'stylesheetComponents':len(names),'initialStylesheets':1}))

if __name__=='__main__':build()
