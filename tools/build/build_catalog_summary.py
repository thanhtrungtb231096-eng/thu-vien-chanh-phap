"""Publish small initial catalog; full provenance is loaded on demand."""
from pathlib import Path
import sys,json
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'app'))
from project_paths import WEB,GENERATED

def build():
    data=json.loads((GENERATED/'dai-tang-kinh/catalog.json').read_text(encoding='utf-8'))
    books=[{**{k:v for k,v in b.items() if k not in ('sources','description')},'sources':[]} for b in data['books']]
    encoded=json.dumps(books,ensure_ascii=False,separators=(',',':'))
    (WEB/'js/dai-tang-kinh-summary.js').write_text('/* Generated by build_catalog_summary.py. */\nwindow.DAI_TANG_KINH_DATA = '+encoded+';\nwindow.DAI_TANG_KINH_GROUPS = '+json.dumps(data['groups'],ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print(json.dumps({'editions':len(books),'summaryBytes':len(encoded.encode('utf-8'))}))

if __name__=='__main__':build()
